package com.leaf.hyperdragshare.codex;

import android.app.Notification;
import android.app.NotificationManager;
import android.app.PendingIntent;
import android.content.Context;
import android.graphics.drawable.Icon;
import android.net.Uri;
import android.os.Binder;
import android.os.Bundle;
import android.os.Handler;
import android.os.Looper;
import android.widget.Toast;

import org.json.JSONArray;
import org.json.JSONException;
import org.json.JSONObject;

import java.util.Arrays;

import de.robv.android.xposed.XC_MethodHook;
import de.robv.android.xposed.XposedBridge;
import de.robv.android.xposed.XposedHelpers;

/** Rewrites only the native MIUI copy-direct card generated by AICR. */
final class AicrCopyHooks {
    private static final String TAG = "DragShare/Aicr";
    private static final String[] NOTIFICATION_HELPER_CLASSES = {"ka6", "d86"};
    private static final String[] ACTION_DATA_CLASSES = {"ha6", "a86"};
    private static final String[] TEXT_COPY_EVENT_CLASSES = {"ul9", "ji9"};
    private static final String[] PERCEPTION_STATE_CLASSES = {"wo2", "jn2"};
    private static final String[] PERCEPTION_KEY_CLASSES = {"n20", "x10"};
    private static final String TEXT_COPY_EVENT_METHOD = "j";
    private static final String NATIVE_CHANNEL_ID = "phrase_channel_id";
    private static final int NATIVE_NOTIFICATION_ID = 111;
    private static final Uri PROVIDER_URI =
            Uri.parse("content://com.leaf.hyperdragshare.codex.share/settings");
    private static final ThreadLocal<PreparedActions> NATIVE_CARD_ACTIONS = new ThreadLocal<>();

    private AicrCopyHooks() {}

    static void install(ClassLoader classLoader) {
        try {
            Class<?> helperClass = findFirstClass(NOTIFICATION_HELPER_CLASSES, classLoader);
            Class<?> actionDataClass = findFirstClass(ACTION_DATA_CLASSES, classLoader);
            if (helperClass == null || actionDataClass == null) {
                log("AICR native notification helper classes were not found; native behavior is unchanged");
                return;
            }
            XposedHelpers.findAndHookMethod(helperClass, "f",
                    Context.class, String.class, int.class, String.class, String.class, actionDataClass,
                    new XC_MethodHook() {
                        @Override
                        protected void beforeHookedMethod(MethodHookParam param) {
                            NATIVE_CARD_ACTIONS.remove();
                            Context context = (Context) param.args[0];
                            String recognizedText = (String) param.args[1];
                            try {
                                Bundle prepared = prepareNativeCardActions(context, recognizedText);
                                if (prepared == null) {
                                    log("copy-direct provider returned no action result");
                                    postToast(context, "复制直达操作准备失败，已保留系统复制卡片");
                                    return;
                                }
                                if (prepared.getBoolean("disabled", false)) return;
                                if (prepared.getBoolean("suppressed", false)) {
                                    param.setResult(null);
                                    return;
                                }
                                if (!prepared.getBoolean("accepted", false)) {
                                    String error = prepared.getString("error", "复制直达操作准备失败");
                                    log("native-card actions unavailable: " + error);
                                    postToast(context, error + "；已保留系统复制卡片");
                                    return;
                                }
                                boolean installGuide = XposedHelpers.getBooleanField(param.args[5], "installGuide");
                                PreparedActions actions = readPreparedActions(context, prepared, installGuide);
                                if (actions == null) {
                                    log("module returned incomplete native-card actions");
                                    postToast(context, "复制直达操作不完整，已保留系统复制卡片");
                                    return;
                                }
                                NATIVE_CARD_ACTIONS.set(actions);
                                if (actions.failure != null) postToast(context, actions.failure);
                            } catch (RuntimeException error) {
                                log("native-card action preparation failed: "
                                        + error.getClass().getSimpleName() + ": " + error.getMessage());
                                postToast(context, "复制直达操作准备失败，已保留系统复制卡片");
                            }
                        }

                        @Override
                        protected void afterHookedMethod(MethodHookParam param) {
                            NATIVE_CARD_ACTIONS.remove();
                        }
                    });
            boolean sourceHookInstalled = hookModuleClipboardSource(classLoader);
            hookNativeNotificationActions();
            log("native copy-direct card hook installed sourceHook=" + sourceHookInstalled + " build="
                    + BuildConfig.VERSION_NAME + "/" + BuildConfig.VERSION_CODE);
        } catch (RuntimeException | LinkageError error) {
            log("native copy-direct card hook unavailable: "
                    + error.getClass().getSimpleName() + ": " + error.getMessage());
        }
    }

    private static boolean hookModuleClipboardSource(ClassLoader classLoader) {
        Class<?> copyEventClass = findFirstClass(TEXT_COPY_EVENT_CLASSES, classLoader);
        if (copyEventClass == null) {
            log("AICR text copy event variants were not found; clipboard source behavior retained");
            return false;
        }
        XposedHelpers.findAndHookMethod(copyEventClass, TEXT_COPY_EVENT_METHOD,
                String.class, String.class, new XC_MethodHook() {
                    @Override
                    protected void beforeHookedMethod(MethodHookParam param) {
                        Object extraArg = param.args[1];
                        if (!(extraArg instanceof String)) return;
                        try {
                            JSONObject extra = new JSONObject((String) extraArg);
                            if (!BuildConfig.APPLICATION_ID.equals(extra.optString("clipSource"))) {
                                return;
                            }
                            String foreground = currentForegroundPackage(classLoader);
                            if (foreground == null || foreground.isEmpty()) {
                                Object eventPackage = XposedHelpers.getObjectField(
                                        param.thisObject, "packageName");
                                foreground = eventPackage instanceof String
                                        ? (String) eventPackage : null;
                            }
                            if (foreground == null || foreground.isEmpty()) {
                                log("module clipboard event retained by native check: foreground package is empty");
                                return;
                            }
                            extra.put("clipSource", foreground);
                            param.args[1] = extra.toString();
                            log("module clipboard event accepted foreground=" + foreground);
                        } catch (JSONException error) {
                            log("module clipboard event extras could not be inspected: "
                                    + error.getClass().getSimpleName());
                        }
                    }
                });
        log("module clipboard source hook installed class=" + copyEventClass.getName());
        return true;
    }

    private static String currentForegroundPackage(ClassLoader classLoader) {
        for (int index = 0; index < PERCEPTION_STATE_CLASSES.length; index++) {
            Class<?> stateClass = XposedHelpers.findClassIfExists(
                    PERCEPTION_STATE_CLASSES[index], classLoader);
            Class<?> keyClass = XposedHelpers.findClassIfExists(
                    PERCEPTION_KEY_CLASSES[index], classLoader);
            if (stateClass == null || keyClass == null) continue;
            Object state = XposedHelpers.getStaticObjectField(stateClass, "INSTANCE");
            Object key = XposedHelpers.getStaticObjectField(keyClass, "KEY_PACKAGE_NAME");
            Object value = XposedHelpers.callMethod(state, "e", key);
            if (value instanceof String && !((String) value).isEmpty()) return (String) value;
        }
        return null;
    }

    private static Class<?> findFirstClass(String[] classNames, ClassLoader classLoader) {
        for (String className : classNames) {
            Class<?> type = XposedHelpers.findClassIfExists(className, classLoader);
            if (type != null) return type;
        }
        return null;
    }

    private static Bundle prepareNativeCardActions(Context context, String recognizedText) {
        if (recognizedText == null || recognizedText.isBlank()) {
            throw new IllegalArgumentException("AICR supplied empty recognized text");
        }
        Bundle input = new Bundle();
        input.putString(IntegrationSettings.EXTRA_TEXT, recognizedText);
        long identity = Binder.clearCallingIdentity();
        try {
            return context.getContentResolver().call(PROVIDER_URI,
                    IntegrationSettings.METHOD_OPEN_AICR_TEXT, null, input);
        } finally {
            Binder.restoreCallingIdentity(identity);
        }
    }

    private static PreparedActions readPreparedActions(Context context, Bundle prepared,
            boolean installGuide) {
        PendingIntent open = prepared.getParcelable(CopyDirectActions.EXTRA_OPEN_PENDING_INTENT);
        PendingIntent segment = prepared.getParcelable(CopyDirectActions.EXTRA_SEGMENT_PENDING_INTENT);
        String openUri = prepared.getString(CopyDirectActions.EXTRA_OPEN_INTENT_URI);
        String segmentUri = prepared.getString(CopyDirectActions.EXTRA_SEGMENT_INTENT_URI);
        Icon icon = prepared.getParcelable(CopyDirectActions.EXTRA_ICON);
        if (segment == null || segmentUri == null || icon == null
                || ((open == null) != (openUri == null))) return null;
        return new PreparedActions(context, open, segment, openUri, segmentUri, icon,
                prepared.getString(CopyDirectActions.EXTRA_TITLE, "打开链接"),
                prepared.getString(CopyDirectActions.EXTRA_CONTENT, ""),
                prepared.getString(CopyDirectActions.EXTRA_FAILURE),
                prepared.getString(CopyDirectActions.EXTRA_KIND, "Text"), installGuide);
    }

    private static void hookNativeNotificationActions() {
        XposedBridge.hookAllMethods(NotificationManager.class, "notify", new XC_MethodHook() {
            @Override
            protected void beforeHookedMethod(MethodHookParam param) {
                if (notificationId(param.args) != NATIVE_NOTIFICATION_ID) return;
                Notification notification = notificationArgument(param.args);
                if (notification == null || !NATIVE_CHANNEL_ID.equals(notification.getChannelId())) return;
                PreparedActions actions = NATIVE_CARD_ACTIONS.get();
                if (actions == null) return;
                NATIVE_CARD_ACTIONS.remove();
                try {
                    rewriteNativeCard(notification, actions);
                    log("replaced AICR native copy-card actions");
                } catch (RuntimeException | JSONException error) {
                    log("native-card action rewrite failed; original AICR card retained: "
                            + error.getClass().getSimpleName() + ": " + error.getMessage());
                    postToast(actions.context, "复制直达卡片修改失败，已保留系统原卡片");
                }
            }
        });
    }

    private static void rewriteNativeCard(Notification notification, PreparedActions actions)
            throws JSONException {
        Bundle extras = notification.extras;
        String focusJson = extras.getString("miui.focus.param");
        if (focusJson == null) throw new JSONException("missing miui.focus.param");
        JSONObject root = new JSONObject(focusJson);
        JSONObject paramV2 = root.optJSONObject("param_v2");
        if (paramV2 == null) throw new JSONException("missing param_v2");
        JSONObject iconTextInfo = paramV2.optJSONObject("iconTextInfo");
        if (iconTextInfo == null) throw new JSONException("missing iconTextInfo");

        boolean preserveNativeCard = !actions.installGuide && "Text".equals(actions.kind);
        JSONArray replacementActions = new JSONArray();
        if (preserveNativeCard) {
            JSONArray originalActions = paramV2.optJSONArray("actions");
            if (originalActions != null) {
                for (int index = 0; index < originalActions.length(); index++) {
                    replacementActions.put(originalActions.get(index));
                }
            }
        } else {
            if (actions.openUri != null && !"Text".equals(actions.kind)) {
                replacementActions.put(focusAction("打开", actions.openUri));
            }
            iconTextInfo.put("title", actions.title);
            iconTextInfo.put("content", actions.content);
        }
        replacementActions.put(focusAction("分词", actions.segmentUri));
        paramV2.put("actions", replacementActions);
        extras.putString("miui.focus.param", root.toString());

        Notification.Action segmentationAction =
                new Notification.Action.Builder(actions.icon, "分词", actions.segment).build();
        if (preserveNativeCard) {
            Notification.Action[] existing = notification.actions == null
                    ? new Notification.Action[0] : notification.actions;
            Notification.Action[] appended = Arrays.copyOf(existing, existing.length + 1);
            appended[existing.length] = segmentationAction;
            notification.actions = appended;
            return;
        }

        extras.putCharSequence(Notification.EXTRA_TITLE, actions.title);
        extras.putCharSequence(Notification.EXTRA_TEXT, actions.content);
        extras.putCharSequence(Notification.EXTRA_BIG_TEXT, actions.content);
        extras.putParcelable("miui.appIcon", actions.icon);
        Bundle pictures = extras.getBundle("miui.focus.pics");
        if (pictures != null) {
            pictures.putParcelable("miui.focus.pic_image", actions.icon);
            pictures.putParcelable("miui.land.pic_image", actions.icon);
            extras.putBundle("miui.focus.pics", pictures);
        }
        notification.contentIntent = actions.open;
        if (actions.open == null || "Text".equals(actions.kind)) {
            notification.actions = new Notification.Action[] {segmentationAction};
        } else {
            notification.actions = new Notification.Action[] {
                    new Notification.Action.Builder(actions.icon, "打开", actions.open).build(),
                    segmentationAction
            };
        }
    }

    private static JSONObject focusAction(String title, String intentUri) throws JSONException {
        JSONObject action = new JSONObject();
        action.put("actionIntent", intentUri);
        action.put("actionIcon", "miui.focus.pic_image");
        action.put("actionTitle", title);
        action.put("actionTitleColor", "#000000");
        action.put("actionTitleColorDark", "#FFFFFF");
        action.put("actionBgColor", "#1A000000");
        action.put("actionBgColorDark", "#1AFFFFFF");
        action.put("actionIntentType", 1);
        action.put("type", 2);
        return action;
    }

    private static Notification notificationArgument(Object[] args) {
        if (args == null) return null;
        for (Object arg : args) if (arg instanceof Notification) return (Notification) arg;
        return null;
    }

    private static int notificationId(Object[] args) {
        if (args == null) return -1;
        for (Object arg : args) if (arg instanceof Integer) return (Integer) arg;
        return -1;
    }

    private static void postToast(Context context, String message) {
        new Handler(Looper.getMainLooper()).post(() -> Toast.makeText(context, message, Toast.LENGTH_LONG).show());
    }

    private static void log(String message) {
        XposedBridge.log(TAG + ": " + message);
    }

    private static final class PreparedActions {
        final Context context;
        final PendingIntent open;
        final PendingIntent segment;
        final String openUri;
        final String segmentUri;
        final Icon icon;
        final String title;
        final String content;
        final String failure;
        final String kind;
        final boolean installGuide;

        PreparedActions(Context context, PendingIntent open, PendingIntent segment, String openUri,
                String segmentUri, Icon icon, String title, String content, String failure,
                String kind, boolean installGuide) {
            this.context = context;
            this.open = open;
            this.segment = segment;
            this.openUri = openUri;
            this.segmentUri = segmentUri;
            this.icon = icon;
            this.title = title;
            this.content = content;
            this.failure = failure;
            this.kind = kind;
            this.installGuide = installGuide;
        }
    }
}
